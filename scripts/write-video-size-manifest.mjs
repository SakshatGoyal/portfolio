import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { videoVariants } from '../src/data/video-variants.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(root, 'worker/video-sizes.generated.ts');
const urls = [...new Set(Object.values(videoVariants).flatMap(({ mobile, desktop }) => [
  mobile.mp4, mobile.webm, desktop.mp4, desktop.webm,
]))].sort();
const sizes = Object.fromEntries(urls.map((url) => [
  url,
  statSync(join(root, 'public', url.replace(/^\//, ''))).size,
]));
const output = `// Generated by scripts/write-video-size-manifest.mjs. Do not edit by hand.\n` +
  `export const GENERATED_VIDEO_BYTES = Object.freeze(${JSON.stringify(sizes, null, 2)} as const);\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== output) {
    console.error('Generated video byte manifest is stale. Run: node scripts/write-video-size-manifest.mjs');
    process.exit(1);
  }
  console.log(`Generated video byte manifest verified for ${urls.length} variants.`);
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote generated video byte manifest for ${urls.length} variants.`);
}
